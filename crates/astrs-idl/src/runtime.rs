    #[test]
    fn a_struct_typed_leaf_with_its_own_sequence_field_encodes_correctly_at_n_greater_than_one() {
        // The scenario `encode_list_rows`/`encode_fixed_list_rows`/
        // `encode_bounded_list_rows` exist for: a message type with its own
        // `Vec`-shaped field, encoded via `ColumnValue::encode_column` with
        // more than one instance at once (as happens whenever that message
        // type is itself used as a sequence element elsewhere).
        #[derive(Debug, Clone, PartialEq)]
        struct Named {
            tags: Vec<String>,
        }

        impl ColumnValue for Named {
            fn value_data_type() -> DataType {
                DataType::strukt([Field::required(
                    "tags",
                    DataType::list(Field::required(ITEM_FIELD, DataType::Utf8)),
                )])
            }

            fn encode_column(values: &[Self]) -> astrs_data::Result<ArrayRef> {
                let rows: Vec<&[String]> = values.iter().map(|v| v.tags.as_slice()).collect();
                let tags_column = encode_list_rows(rows.into_iter())?;
                let DataType::Struct(fields) = Self::value_data_type() else {
                    return Err(DataError::type_mismatch(
                        Self::value_data_type(),
                        DataType::Null,
                    ));
                };
                let strukt =
                    StructArray::try_new_with_len(fields, vec![tags_column], values.len(), None)?;
                Ok(strukt.into_array_ref())
            }

            fn decode_row(
                array: &ArrayRef,
                row: usize,
                field_name: &'static str,
            ) -> astrs_data::Result<Self> {
                let tags_column = struct_column(array, 0, 1)?;
                let tags = decode_list_column::<String>(tags_column, row, field_name)?;
                Ok(Self { tags })
            }
        }

        let values = vec![
            Named {
                tags: vec!["a".to_owned(), "b".to_owned()],
            },
            Named { tags: Vec::new() },
            Named {
                tags: vec!["c".to_owned()],
            },
        ];
        // Encoded as a *sequence element* — N = 3 rows in one call, which is
        // exactly the case a naive single-row helper would get wrong.
        let column = encode_list_column(&values).unwrap();
        assert_eq!(
            decode_list_column::<Named>(&column, 0, "items").unwrap(),
            values
        );
    }

