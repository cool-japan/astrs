    #[test]
    fn nested_message_leaves_compose_through_encode_column_and_struct_column() {
        // A minimal stand-in for what codegen emits for a two-field struct,
        // proving the `struct_column` + per-field `ColumnValue` composition
        // without depending on `crate::codegen`.
        #[derive(Debug, Clone, Copy, PartialEq)]
        struct Pair {
            left: i32,
            right: i32,
        }

        impl ColumnValue for Pair {
            fn value_data_type() -> DataType {
                DataType::strukt([
                    Field::required("left", DataType::Int32),
                    Field::required("right", DataType::Int32),
                ])
            }

            fn encode_column(values: &[Self]) -> astrs_data::Result<ArrayRef> {
                let lefts: Vec<i32> = values.iter().map(|v| v.left).collect();
                let rights: Vec<i32> = values.iter().map(|v| v.right).collect();
                let columns = vec![i32::encode_column(&lefts)?, i32::encode_column(&rights)?];
                let DataType::Struct(fields) = Self::value_data_type() else {
                    return Err(DataError::type_mismatch(
                        Self::value_data_type(),
                        DataType::Null,
                    ));
                };
                let strukt = StructArray::try_new_with_len(fields, columns, values.len(), None)?;
                Ok(strukt.into_array_ref())
            }

            fn decode_row(
                array: &ArrayRef,
                row: usize,
                field_name: &'static str,
            ) -> astrs_data::Result<Self> {
                let left = i32::decode_row(struct_column(array, 0, 2)?, row, "left")?;
                let right = i32::decode_row(struct_column(array, 1, 2)?, row, "right")?;
                let _ = field_name;
                Ok(Self { left, right })
            }
        }

        let values = vec![
            Pair { left: 1, right: 2 },
            Pair { left: 3, right: 4 },
            Pair { left: 5, right: 6 },
        ];

        // As a scalar (one row): the `N = 1` case.
        let scalar_column = Pair::encode_column(&values[..1]).unwrap();
        assert_eq!(
            Pair::decode_row(&scalar_column, 0, "pair").unwrap(),
            values[0]
        );

        // As a sequence element: `Vec<Pair>` via the generic list helpers.
        let list_column = encode_list_column(&values).unwrap();
        assert_eq!(
            decode_list_column::<Pair>(&list_column, 0, "pairs").unwrap(),
            values
        );

        // `N = 0` needs no special case.
        let empty_column = Pair::encode_column(&[]).unwrap();
        assert_eq!(empty_column.len(), 0);
    }
